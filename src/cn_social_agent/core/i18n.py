# Language names presented to the user, always in their own language.
_LOCALE_NAMES = {
    "zh-CN": {"zh-CN": "简体中文", "en-US": "English"},
    "en-US": {"zh-CN": "Simplified Chinese", "en-US": "English"},
}


def available_locales() -> list[dict[str, str]]:
    return [
        {"code": code, "name": _LOCALE_NAMES.get(code, {}).get(code, code)}
        for code in SUPPORTED_LOCALES
    ]


def translate(key: str, locale: Optional[str] = None, **params: Any) -> str:
    """Look up ``key`` in ``locale``, falling back to zh-CN then the key itself."""
    effective = normalize_locale(locale) if locale else _resolve_locale()
    table = _TRANSLATIONS.get(effective) or {}
    value = table.get(key)
    if value is None and effective != _FALLBACK:
        value = _TRANSLATIONS.get(_FALLBACK, {}).get(key)
    if value is None:
        return key
    if params:
        try:
            return value.format(**params)
        except (KeyError, IndexError):
            return value
    return value


def _resolve_locale() -> str:
    ctx = current()
    return ctx.locale if ctx else DEFAULT_LOCALE


def t(key: str, **params: Any) -> str:
    """Translate using the active tenant's locale."""
    return translate(key, **params)


def dictionary(locale: Optional[str] = None) -> dict[str, str]:
    effective = normalize_locale(locale) if locale else _resolve_locale()
    base = dict(_TRANSLATIONS.get(_FALLBACK, {}))
    if effective != _FALLBACK:
        base.update(_TRANSLATIONS.get(effective, {}))
    return base


# Language directives injected into expert prompts so output follows the locale.
_OUTPUT_LANGUAGE_HINT = {
    "zh-CN": "Respond in Simplified Chinese (简体中文).",
    "en-US": "Respond in English.",
}


def output_language_hint(locale: Optional[str] = None) -> str:
    effective = normalize_locale(locale) if locale else _resolve_locale()
    return _OUTPUT_LANGUAGE_HINT.get(effective, _OUTPUT_LANGUAGE_HINT[DEFAULT_LOCALE])
